using System;
using System.Collections.Generic;
using System.Linq;

namespace SysadminsLV.WPF.Tests.Layering;

/// <summary>
/// The single place that assigns library namespaces and XAML directories to architecture layers.
/// </summary>
public static class LayerMap {
    const String Root = "SysadminsLV.WPF";
    // namespaces that have not been moved to the new structure yet
    const String LegacyRoot = Root + ".OfficeTheme";

    /// <summary>
    /// Level of the layer that contains XAML theme resources. XAML has no CLR namespace, so it is assigned by directory.
    /// </summary>
    public const Int32 ThemeLevel = 5;

    /// <summary>
    /// All layers, ordered from the lowest to the highest.
    /// </summary>
    public static readonly IReadOnlyList<Layer> Layers = [
        // The legacy entry in this layer is temporary: Toolkit.Commands still holds DialogCloser (moves to behaviors).
        new Layer(1, "Mvvm and collections", [
            $"{Root}.Mvvm",
            $"{Root}.Mvvm.Commands",
            $"{Root}.Collections",
            $"{LegacyRoot}.Toolkit.Commands"
        ]),
        new Layer(2, "Dialogs and logging", [
            $"{Root}.Dialogs",
            $"{Root}.Logging"
        ]),
        new Layer(3, "Behaviors and converters", [
            $"{LegacyRoot}.Toolkit.Behaviors",
            $"{LegacyRoot}.Toolkit.Converters"
        ]),
        new Layer(4, "Controls", [
            $"{LegacyRoot}.Controls"
        ]),
        new Layer(ThemeLevel, "Theme (XAML)", [])
    ];

    /// <summary>
    /// Maps directories of the library project that contain XAML to the level of the layer they belong to.
    /// </summary>
    public static readonly IReadOnlyDictionary<String, Int32> XamlDirectories = new Dictionary<String, Int32>(StringComparer.OrdinalIgnoreCase) {
        ["UI"] = ThemeLevel
    };

    /// <summary>
    /// Namespaces generated by the XAML compiler. They are not part of the architecture.
    /// </summary>
    public static readonly IReadOnlyList<String> GeneratedNamespaces = ["XamlGeneratedNamespace"];

    /// <summary>
    /// Gets all namespaces of the layers that are strictly above the specified level.
    /// </summary>
    /// <param name="level">
    /// Level to start from.
    /// </param>
    /// <returns>
    /// Namespaces of all higher layers.
    /// </returns>
    public static String[] NamespacesAbove(Int32 level) {
        return Layers
            .Where(x => x.Level > level)
            .SelectMany(x => x.Namespaces)
            .ToArray();
    }
    /// <summary>
    /// Gets the level of the layer that owns the specified namespace.
    /// </summary>
    /// <param name="clrNamespace">
    /// CLR namespace to look up (exact match).
    /// </param>
    /// <returns>
    /// Layer level, or <c>null</c> if the namespace is not in the map.
    /// </returns>
    public static Int32? LevelOf(String clrNamespace) {
        return Layers
            .Where(x => x.Namespaces.Contains(clrNamespace))
            .Select(x => (Int32?)x.Level)
            .FirstOrDefault();
    }
}
